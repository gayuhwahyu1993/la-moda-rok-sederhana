// Helper to format practical drafting numbers without trailing zeros
export function formatDraftingPrecision(val: number): string {
  if (Number.isInteger(val)) {
    return val.toString();
  }
  // Check if repeating decimals (e.g. 1/3 = 0.3333..., 2/3 = 0.6666...)
  const str = val.toString();
  if (str.includes('33333') || str.includes('66666') || str.includes('99999') || str.includes('11111') || str.includes('77777')) {
    return parseFloat(val.toFixed(2)).toString();
  }
  // For exact fractions (e.g., .125, .6875, .53125), show up to 5 clean decimal places
  return parseFloat(val.toFixed(5)).toString();
}

